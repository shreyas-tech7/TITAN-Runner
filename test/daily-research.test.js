test('the shipped topics file loads; rotation is deterministic and covers a long list over days; malformed files give no topics and a warning', () => {
  const shipped = loadResearchTopics();
  assert.deepEqual(shipped.warnings, []);
  assert.equal(shipped.source, 'config/research-topics.yml');
  assert.equal(shipped.topics.length, 3);
  assert.equal(shipped.maxTopics, 3);
  assert.ok(existsSync(DEFAULT_TOPICS_PATH));

  const five = ['a', 'b', 'c', 'd', 'e'].map((id) => ({ id, prompt: id }));
  const seen = new Set();
  for (let day = 0; day < 5; day++) {
    const picked = pickTopics(five, 2, new Date(Date.UTC(2026, 5, 10 + day)));
    assert.equal(picked.length, 2);
    picked.forEach((t) => seen.add(t.id));
    assert.deepEqual(picked, pickTopics(five, 2, new Date(Date.UTC(2026, 5, 10 + day, 23, 59))), 'same day, same topics');
  }
  assert.equal(seen.size, 5);
  assert.equal(pickTopics(five, 9, DAY1).length, 5);

  const dir = mkdtempSync(join(tmpdir(), 'titan-topics-'));
  try {
    const file = join(dir, 't.yml');
    assert.deepEqual(loadResearchTopics({ path: join(dir, 'nope.yml') }), { topics: [], maxTopics: 0, source: 'none', warnings: [] });
    for (const text of ['version: 2\n', 'version: 1\ntopics:\n  - a\n', 'version: 1\n', 'version: 1\ntopics:\n  a: [x]\n']) {
      writeFileSync(file, text);
      const r = loadResearchTopics({ path: file });
      assert.equal(r.topics.length, 0, text);
      assert.equal(r.warnings.length, 1, text);
    }
    writeFileSync(file, 'version: 1\nmax_topics: 99\ntopics:\n  ok: "fine"\n  empty: ""\n  num: 5\n');
    const partial = loadResearchTopics({ path: file });
    assert.deepEqual(partial.topics, [{ id: 'ok', prompt: 'fine' }]);
    assert.equal(partial.maxTopics, 6, 'capped');
    assert.equal(partial.warnings.length, 2);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }

  assert.match(buildResearchMessages(five.slice(0, 2), '2026-06-10')[1].content, /1\. a: a\n2\. b: b/);
  assert.equal(researchEnabledFromEnv({}), true);
  assert.equal(researchEnabledFromEnv({ TITAN_RESEARCH: '0' }), false);
  assert.equal(researchEnabledFromEnv({ TITAN_RESEARCH: '1' }), true);
});

