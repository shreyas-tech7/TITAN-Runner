/**
 * The daily research digest (src/research/dailyResearch.js): once per UTC
 * day, one low-priority call, written to state/digests/, and — above all —
 * never able to fail the pulse when every free provider is rate-limited.
 * Zero network: the registry is a fake.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync, existsSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StateStore } from '../src/state/store.js';
import {
  runDailyResearch, loadResearchTopics, pickTopics, buildResearchMessages, sanitizeDigestBody, researchEnabledFromEnv, DEFAULT_TOPICS_PATH,
} from '../src/research/dailyResearch.js';
import { parseSafetyRules } from '../src/policy/safetyRules.js';
import { runPulse } from '../src/engine/pulse.js';
import { FakeProviderAgent } from '../src/fakes/fakeProvider.js';
import { FakeGitHub } from '../src/fakes/fakeGitHub.js';

const DAY1 = new Date('2026-06-10T06:05:00.000Z');
const GOOD_BODY = [
  '## free-tier-llm-landscape', '- Limits move often.', '- An agent that only uses free tiers must re-discover models.', '- Verify current per-minute caps.',
  '## agent-safety-practice', '- Approval tiers.', '- They keep irreversible actions human-gated.', '- Verify your own audit log covers them.',
].join('\n');

function fakeRegistry({ configured = ['groq'], reply = { text: GOOD_BODY, service: 'groq', model: 'llama-test' }, failWith = null } = {}) {
  const calls = [];
  return {
    calls,
    configuredIds: () => configured,
    async chat(messages, opts) {
      calls.push({ messages, opts });
      if (failWith) throw failWith;
      return typeof reply === 'function' ? reply() : reply;
    },
  };
}
const allFailed = (failureClass) => Object.assign(new Error('All providers failed for this request (tried: groq, together)'), { code: 'ALL_PROVIDERS_FAILED', failureClass });

function world() {
  const stateDir = mkdtempSync(join(tmpdir(), 'titan-research-'));
  const store = new StateStore({ stateDir });
  store.ensureLayout();
  const events = [];
  const sink = { append: (type, data) => events.push({ type, ...data }) };
  return {
    stateDir, store, events, sink,
    digest: (date = '2026-06-10') => join(stateDir, 'digests', `${date}-research.md`),
    digests: () => (existsSync(join(stateDir, 'digests')) ? readdirSync(join(stateDir, 'digests')).filter((f) => f.endsWith('-research.md')) : []),
    state: () => JSON.parse(readFileSync(join(stateDir, 'research.json'), 'utf8')),
    view: () => JSON.parse(readFileSync(join(stateDir, 'views', 'research.json'), 'utf8')),
    cleanup: () => rmSync(stateDir, { recursive: true, force: true }),
  };
}
const run = (w, registry, over = {}) => runDailyResearch({ store: w.store, registry, now: () => DAY1, events: w.sink, control: {}, ...over });

test('writes one digest to state/digests/, labelled as model knowledge with no web access, and surfaces it in a view', async () => {
  const w = world();
  try {
    const registry = fakeRegistry();
    const r = await run(w, registry);
    assert.deepEqual([r.status, r.reason, r.file, r.provider, r.model], ['written', 'ok', 'state/digests/2026-06-10-research.md', 'groq', 'llama-test']);

    // One lightweight, LOW-priority call over the existing pool, bounded.
    assert.equal(registry.calls.length, 1);
    const { messages, opts } = registry.calls[0];
    assert.equal(opts.priority, 'low');
    assert.ok(opts.maxTokens <= 700 && opts.maxProviders <= 2);
    assert.match(messages[1].content, /Date: 2026-06-10/);
    for (const id of ['free-tier-llm-landscape', 'agent-safety-practice', 'actions-automation']) assert.ok(messages[1].content.includes(id), id);
    assert.match(messages[0].content, /no web access/);

    const text = readFileSync(w.digest(), 'utf8');
    assert.match(text, /^# Research digest — 2026-06-10/);
    assert.match(text, /Generated by TITAN-Runner at 2026-06-10T06:05:00\.000Z using groq \(llama-test\)/);
    assert.match(text, /no web access and cited no live sources/);
    assert.ok(text.includes('- Limits move often.'));

    assert.deepEqual([w.state().lastStatus, w.state().lastDigestDate, w.state().lastDigestFile], ['written', '2026-06-10', 'state/digests/2026-06-10-research.md']);
    const view = w.view();
    assert.equal(view.lastStatus, 'written');
    assert.equal(view.digest.date, '2026-06-10');
    assert.ok(view.digest.preview.includes('Limits move often'));
    assert.deepEqual(w.events.map((e) => [e.type, e.outcome]), [['research.written', 'written']]);
  } finally {
    w.cleanup();
  }
});

test('once per UTC day: a second run the same day does not call a provider; the next day writes a new digest', async () => {
  const w = world();
  try {
    const registry = fakeRegistry();
    await run(w, registry);
    const again = await run(w, registry, { now: () => new Date('2026-06-10T23:59:00.000Z') });
    assert.deepEqual([again.status, again.reason], ['skipped', 'already-written']);
    assert.equal(registry.calls.length, 1, 'no second model call');
    // Even with research.json lost, the existing digest file is what counts.
    rmSync(join(w.stateDir, 'research.json'));
    assert.equal((await run(w, registry)).reason, 'already-written');
    assert.equal(registry.calls.length, 1);

    const next = await run(w, registry, { now: () => new Date('2026-06-11T06:05:00.000Z') });
    assert.equal(next.status, 'written');
    assert.equal(registry.calls.length, 2);
    assert.deepEqual(w.digests().sort(), ['2026-06-10-research.md', '2026-06-11-research.md']);
  } finally {
    w.cleanup();
  }
});

test('every free provider rate-limited: skipped silently — no digest, no throw, recorded once, and retried only after the backoff', async () => {
  const w = world();
  try {
    const limited = fakeRegistry({ failWith: allFailed('rate_limited') });
    const r = await run(w, limited);
    assert.deepEqual([r.status, r.reason], ['skipped', 'rate_limited']);
    assert.deepEqual(w.digests(), []);
    assert.deepEqual([w.state().lastStatus, w.state().lastReason], ['skipped', 'rate_limited']);
    assert.equal(w.state().lastDigestDate, undefined);
    assert.deepEqual(w.events.map((e) => [e.type, e.reason]), [['research.skipped', 'rate_limited']]);
    assert.equal(w.view().digest, null);

    // The next pulse, 15 minutes later: backoff, no provider call.
    const soon = await run(w, limited, { now: () => new Date(DAY1.getTime() + 15 * 60_000) });
    assert.deepEqual([soon.status, soon.reason], ['skipped', 'backoff']);
    assert.equal(limited.calls.length, 1);

    // After the window (default 3h) it tries again — and succeeds once a provider recovers.
    const recovered = fakeRegistry();
    const later = await run(w, recovered, { now: () => new Date(DAY1.getTime() + 181 * 60_000) });
    assert.equal(later.status, 'written');
    assert.equal(w.state().lastStatus, 'written');
    assert.equal(w.view().digest.date, '2026-06-10');

    // A custom retry window is honoured.
    const w2 = world();
    try {
      await run(w2, limited);
      const r2 = await run(w2, fakeRegistry(), { now: () => new Date(DAY1.getTime() + 11 * 60_000), retryMinutes: 10 });
      assert.equal(r2.status, 'written');
    } finally {
      w2.cleanup();
    }
  } finally {
    w.cleanup();
  }
});

test('failures of every shape are skipped, never thrown: provider down, timeout, empty, too-short, and a registry that explodes', async () => {
  for (const [label, registry, reason] of [
    ['provider down', fakeRegistry({ failWith: allFailed('provider_down') }), 'provider_down'],
    ['no class', fakeRegistry({ failWith: Object.assign(new Error('boom'), { code: 'UPSTREAM_ERROR' }) }), 'UPSTREAM_ERROR'],
    ['plain error', fakeRegistry({ failWith: new Error('boom') }), 'provider-error'],
    ['empty text', fakeRegistry({ reply: { text: '', service: 'groq', model: 'm' } }), 'empty-response'],
    ['tiny text', fakeRegistry({ reply: { text: 'ok', service: 'groq', model: 'm' } }), 'empty-response'],
    ['null reply', fakeRegistry({ reply: null }), 'empty-response'],
    ['exploding configuredIds', { configuredIds() { throw new Error('kaboom'); }, chat: async () => { throw new Error('unreachable'); } }, 'error'],
  ]) {
    const w = world();
    try {
      const r = await run(w, registry);
      assert.deepEqual([r.status, r.reason], ['skipped', reason], label);
      assert.deepEqual(w.digests(), [], label);
    } finally {
      w.cleanup();
    }
  }
});

test('quiet skips write nothing and emit nothing: no provider configured, disabled, dry-run, kill switch, drain, autonomy dry-run, out of pulse budget', async () => {
  const cases = [
    ['no provider', fakeRegistry({ configured: [] }), {}, 'no-provider'],
    ['disabled', fakeRegistry(), { enabled: false }, 'disabled'],
    ['dry-run', fakeRegistry(), { dryRun: true }, 'dry-run'],
    ['kill switch', fakeRegistry(), { control: { killSwitch: true } }, 'kill-switch'],
    ['drain', fakeRegistry(), { control: { drain: true } }, 'drain'],
    ['autonomy dry-run', fakeRegistry(), { control: { autonomy: 'dry-run' } }, 'autonomy-dry-run'],
    ['pulse budget', fakeRegistry(), { shouldStop: () => true }, 'pulse-budget'],
    ['no topics', fakeRegistry(), { topicsConfig: { topics: [], maxTopics: 3, warnings: [] } }, 'no-topics'],
  ];
  for (const [label, registry, over, reason] of cases) {
    const w = world();
    try {
      const r = await run(w, registry, over);
      assert.deepEqual([r.status, r.reason], ['skipped', reason], label);
      assert.equal(registry.calls.length, 0, `${label}: no model call`);
      assert.equal(existsSync(join(w.stateDir, 'research.json')), false, `${label}: no state written`);
      assert.deepEqual(w.events, [], `${label}: no event`);
      assert.deepEqual(w.digests(), [], label);
    } finally {
      w.cleanup();
    }
  }
});

test('the digest is a state append: if the safety rules stop auto-approving that, research does not run', async () => {
  const w = world();
  try {
    const strict = parseSafetyRules('version: 1\nauto_approve:\n  - read\nalways_ask:\n  - state-append\n');
    const registry = fakeRegistry();
    const r = await run(w, registry, { rules: strict });
    assert.deepEqual([r.status, r.reason], ['skipped', 'safety-rules']);
    assert.equal(registry.calls.length, 0);
    // With the shipped rules it runs.
    assert.equal((await run(w, registry)).status, 'written');
  } finally {
    w.cleanup();
  }
});

test('model output is scrubbed before it reaches a public repo: credentials, emails, a wrapping code fence, and runaway length', async () => {
  const dirty = ['```markdown', '## t', '- key ghp_abcdefghijklmnopqrstuvwxyz0123456789 and mail someone@example.com', '- ok'.padEnd(200, '.'), '```'].join('\n');
  const w = world();
  try {
    await run(w, fakeRegistry({ reply: { text: dirty, service: 'groq', model: 'm' } }));
    const text = readFileSync(w.digest(), 'utf8');
    assert.ok(!text.includes('ghp_abcdefghijklmnopqrstuvwxyz0123456789'));
    assert.ok(!text.includes('someone@example.com'));
    assert.ok(!text.includes('```'));
    assert.ok(!JSON.stringify(w.view()).includes('ghp_abc'));
  } finally {
    w.cleanup();
  }
  const long = sanitizeDigestBody(`## t\n${'word '.repeat(5000)}`);
  assert.ok(long.length < 6100 && long.endsWith('_(truncated)_'));
  assert.equal(sanitizeDigestBody(undefined), '');
});

test('a later skipped attempt does not blank the last digest the dashboard shows', async () => {
  const w = world();
  try {
    await run(w, fakeRegistry());
    const tomorrow = new Date('2026-06-11T06:05:00.000Z');
    await run(w, fakeRegistry({ failWith: allFailed('rate_limited') }), { now: () => tomorrow });
    const view = w.view();
    assert.equal(view.lastStatus, 'skipped');
    assert.equal(view.lastReason, 'rate_limited');
    assert.equal(view.digest.date, '2026-06-10', 'still points at the last real digest');
    assert.ok(view.digest.preview.includes('Limits move often'));
  } finally {
    w.cleanup();
  }
});

