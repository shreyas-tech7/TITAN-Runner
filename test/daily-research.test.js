function pulseWorld() {
  const stateDir = mkdtempSync(join(tmpdir(), 'titan-research-pulse-'));
  const repoRoot = mkdtempSync(join(tmpdir(), 'titan-repo-'));
  mkdirSync(join(repoRoot, 'src'));
  const github = new FakeGitHub({ fixture: { issues: [] }, repository: 'owner-login/repo', now: () => DAY1 });
  const fake = new FakeProviderAgent({ script: { seed: 1, latencyMs: [1, 2], rules: [{ kind: '*', sequence: [{ reply: 'prose', text: 'x' }] }] }, quiet: true });
  const deps = (extra = {}) => ({ stateDir, repoRoot, github, pools: { phase2: fake }, reviewerChat: fake.chat.bind(fake), dryRun: false, now: () => DAY1, ...extra });
  return { stateDir, deps, cleanup: () => { rmSync(stateDir, { recursive: true, force: true }); rmSync(repoRoot, { recursive: true, force: true }); } };
}

test('through runPulse: the digest is written once a day, and a rate-limited day costs the pulse nothing', async () => {
  const w = pulseWorld();
  try {
    const registry = fakeRegistry();
    const a = await runPulse(w.deps({ pulseId: 'p1', research: { enabled: true, registry } }));
    assert.equal(a.error, null);
    assert.ok(existsSync(join(w.stateDir, 'digests', '2026-06-10-research.md')));
    assert.ok(existsSync(join(w.stateDir, 'views', 'research.json')));
    await runPulse(w.deps({ pulseId: 'p2', research: { enabled: true, registry } }));
    assert.equal(registry.calls.length, 1, 'the second pulse that day made no research call');

    // A fresh day where every provider is rate-limited: the pulse still succeeds, nothing new is written.
    const limited = fakeRegistry({ failWith: allFailed('rate_limited') });
    const b = await runPulse(w.deps({ pulseId: 'p3', now: () => new Date('2026-06-11T06:05:00.000Z'), research: { enabled: true, registry: limited } }));
    assert.equal(b.error, null, 'a rate-limited research pass must not fail the pulse');
    assert.equal(limited.calls.length, 1);
    assert.ok(!existsSync(join(w.stateDir, 'digests', '2026-06-11-research.md')));
    const hb = JSON.parse(readFileSync(join(w.stateDir, 'heartbeat.json'), 'utf8'));
    assert.equal(hb.lastPulseStatus, 'ok');
  } finally {
    w.cleanup();
  }
});

test('through runPulse: research stays off when fakes are injected unless a caller turns it on, and in dry-run', async () => {
  const w = pulseWorld();
  try {
    const registry = fakeRegistry();
    // deps.research.registry alone does not enable it while pools/github are injected.
    await runPulse(w.deps({ pulseId: 'p1', research: { registry } }));
    assert.equal(registry.calls.length, 0);
    await runPulse(w.deps({ pulseId: 'p2', dryRun: true, research: { enabled: true, registry } }));
    assert.equal(registry.calls.length, 0, 'dry-run makes no model call');
    await runPulse(w.deps({ pulseId: 'p3', research: { enabled: false, registry } }));
    assert.equal(registry.calls.length, 0);
    assert.equal(existsSync(join(w.stateDir, 'digests')) ? readdirSync(join(w.stateDir, 'digests')).filter((f) => f.endsWith('-research.md')).length : 0, 0);
  } finally {
    w.cleanup();
  }
});
