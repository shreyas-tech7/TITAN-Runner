#!/usr/bin/env node
/**
 * @file Builds `worker/src/migrations.generated.js` from `worker/migrations/*.sql` (Wave 12, K9 and X2).
 *
 * The deploy workflow applies the migrations with wrangler. The Worker also holds the same SQL, so it can
 * apply a missing migration on its first tick if the deploy step could not. Both paths use the table
 * `d1_migrations`, which is the table that wrangler uses, so they never apply the same file twice.
 *
 * Usage: node scripts/gen-worker-migrations.mjs [--check]
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = 'worker/migrations';
const out = 'worker/src/migrations.generated.js';
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();

/** Split a migration into statements. The files avoid a semicolon inside a string or a trigger. */
export function splitStatements(sql) {
  const stripped = sql
    .split('\n')
    .filter((line) => !line.trim().startsWith('--'))
    .join('\n');
  return stripped
    .split(/;\s*(?:\n|$)/)
    .map((s) => s.trim())
    .filter(Boolean);
}

const entries = files.map((f) => ({ name: f, statements: splitStatements(readFileSync(`${dir}/${f}`, 'utf8')) }));
const text = `// Generated by scripts/gen-worker-migrations.mjs from worker/migrations/*.sql. Do not edit by hand.\n// Run: node scripts/gen-worker-migrations.mjs\n/** @type {Array<{ name: string, statements: string[] }>} */\nexport const MIGRATIONS = ${JSON.stringify(entries, null, 2)};\n\nexport const SCHEMA_VERSION = ${entries.length};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    // missing
  }
  if (current !== text) {
    console.error('gen-worker-migrations: worker/src/migrations.generated.js is stale. Run: node scripts/gen-worker-migrations.mjs');
    process.exit(1);
  }
  console.log(`gen-worker-migrations: in sync (${entries.length} migration files).`);
} else {
  writeFileSync(out, text);
  console.log(`gen-worker-migrations: wrote ${entries.length} migration(s) to ${out}`);
}
